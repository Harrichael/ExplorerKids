// 'Name emoji' or 'Name emoji eats A, B, C'; the emoji is the last word before "eats"
function parseWeb(w){
  const species = w.web.map(line => {
    const [who, food] = line.split(/ eats? /), sp = who.lastIndexOf(' ');
    return {name: who.slice(0, sp), icon: who.slice(sp + 1), eats: food ? food.split(', ') : []};
  });
  const names = new Set(species.map(s => s.name));
  for (const s of species) for (const f of s.eats) if (!names.has(f)) throw new Error(`${w.id}: ${s.name} eats unknown "${f}"`);
  return {id: w.id, place: w.place, at: w.at, realm: w.realm, biomes: w.biomes, species};
}
export const WEBS = WEB_LIST.map(parseWeb);

// a spot in the biome, to take an explorer there
export const visit = id => BIOMES[id].visit || WEBS.find(w => w.biomes.includes(id)).at;
