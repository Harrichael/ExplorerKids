// 'Name emoji', 'Name emoji eats A, B, C', or with what it only sometimes eats, 'Name emoji eats A, B; sometimes C';
// the emoji is the last word before "eats"
function parseWeb(w){
  const species = w.web.map(line => {
    const [who, food] = line.split(/ eats? /), sp = who.lastIndexOf(' '), [often, rarely] = (food || '').split('; sometimes ');
    return {name: who.slice(0, sp), icon: who.slice(sp + 1), eats: often ? often.split(', ') : [], sometimes: rarely ? rarely.split(', ') : [], many: / eat /.test(line)};
  });
  const names = new Set(species.map(s => s.name));
  for (const s of species) for (const f of [...s.eats, ...s.sometimes]) if (!names.has(f)) throw new Error(`${w.id}: ${s.name} eats unknown "${f}"`);
  return {id: w.id, place: w.place, at: w.at, realms: [w.realm].flat().filter(Boolean), biomes: w.biomes, bounds: w.bounds, waters: w.waters, species};
}
export const WEBS = WEB_LIST.map(parseWeb);

